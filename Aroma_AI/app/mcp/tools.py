def create_simulated_db(menu_data, table_data):
    menus = {}
    for category in menu_data.get('data', []):
        category_type = category.get('item_type')
        items = category.get('items', [])
        item_list = [
            {"id": item.get('id'), "item_name": item.get('item_name'), "price": item.get('price')}
            for item in items if item.get('is_available', False)
        ]
        menus[category_type] = item_list
    
    # Extract available tables as "T" + number
    tables = ["T" + str(table.get('number')) for table in table_data.get('data', []) if table.get('status') == "available"]

    # Hardcode delivery boys as per the example
    delivery_boys = [
        {"name": "Parth Bhai", "available": False},
        {"name": "OG Sanskar Bhai", "available": True},
        {"name": "Achal Bhai", "available": True}
    ]

    # Initialize previous_orders as an empty dict
    previous_orders = {}

    # Return the simulated_db
    simulated_db = {
        "menus": menus,
        "tables": tables,
        "delivery_boys": delivery_boys,
        "previous_orders": previous_orders
    }

    return simulated_db

